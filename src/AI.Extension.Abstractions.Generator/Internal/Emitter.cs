using System.Collections.Generic;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace AI.Extension.Abstractions.Generator.Internal;

/// <summary>把契约模型渲染成 C# 源码。</summary>
internal static class Emitter
{
    private const string GeneratorName = "AI.Extension.Abstractions.Generator";
    private const string GeneratorVersion = "0.1.0";
    private const string GeneratedRootNamespace = "AI.Extension.Generated";

    public static void Emit(SourceProductionContext context, ContractCollection collection)
    {
        foreach (DiagnosticInfo diagnostic in collection.Diagnostics)
        {
            Diagnostics.Report(context, diagnostic);
        }

        foreach (ContractSpec contract in collection.Contracts)
        {
            context.AddSource(
                HintName(contract),
                SourceText.From(EmitBridge(contract), Encoding.UTF8));
        }

        context.AddSource(
            "AiContractBridgeRegistration.g.cs",
            SourceText.From(EmitRegistration(collection.Contracts), Encoding.UTF8));
    }

    private static string HintName(ContractSpec contract)
        => Sanitize(contract.BridgeNamespace) + "_" + contract.BridgeName + ".g.cs";

    private static string Sanitize(string value)
    {
        var builder = new StringBuilder(value.Length);
        foreach (char character in value)
        {
            builder.Append(char.IsLetterOrDigit(character) ? character : '_');
        }

        return builder.ToString();
    }

    private static string EmitBridge(ContractSpec contract)
    {
        var builder = new StringBuilder(4096);

        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("// 由 AI.Extension.Abstractions.Generator 生成，请勿手工修改。");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("#pragma warning disable CS1591");
        builder.AppendLine();
        builder.Append("namespace ").Append(contract.BridgeNamespace).AppendLine(";");
        builder.AppendLine();

        builder.AppendLine("[global::System.CodeDom.Compiler.GeneratedCode(" +
                           ContractCollectorFormatting.Literal(GeneratorName) + ", " +
                           ContractCollectorFormatting.Literal(GeneratorVersion) + ")]");
        builder.AppendLine("[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
        builder.Append("public sealed partial class ").Append(contract.BridgeName)
            .AppendLine(" : global::AI.Extension.IAiContractBridge");
        builder.AppendLine("{");

        builder.Append("    private readonly ").Append(contract.InterfaceFullName).AppendLine(" _contract;");
        builder.AppendLine();
        builder.Append("    /// <summary>构造桥接。契约实现由 DI 容器注入（通常注册在组合根中）。</summary>");
        builder.AppendLine();
        builder.Append("    public ").Append(contract.BridgeName).Append('(').Append(contract.InterfaceFullName).AppendLine(" contract)");
        builder.AppendLine("    {");
        builder.AppendLine("        _contract = contract ?? throw new global::System.ArgumentNullException(nameof(contract));");
        builder.AppendLine("    }");
        builder.AppendLine();

        builder.Append("    /// <inheritdoc />").AppendLine();
        builder.Append("    public global::System.Type ContractType => typeof(").Append(contract.InterfaceFullName).AppendLine(");");
        builder.AppendLine();

        builder.Append("    /// <inheritdoc />").AppendLine();
        builder.Append("    public string ContractName => ").Append(ContractCollectorFormatting.Literal(contract.ContractName)).AppendLine(";");
        builder.AppendLine();

        builder.AppendLine("    /// <inheritdoc />");
        builder.AppendLine("    public global::System.Collections.Generic.IReadOnlyList<global::AI.Extension.AiBridgeMethod> Methods { get; } =");
        builder.AppendLine("        new global::AI.Extension.AiBridgeMethod[]");
        builder.AppendLine("        {");
        foreach (MethodSpec method in contract.Methods)
        {
            builder.Append("            new global::AI.Extension.AiBridgeMethod(")
                .Append(ContractCollectorFormatting.Literal(method.Name)).Append(", ")
                .Append(ContractCollectorFormatting.Literal(method.Description)).Append(", ")
                .Append(ContractCollectorFormatting.Literal(method.SuggestedToolName)).AppendLine("),");
        }

        builder.AppendLine("        };");
        builder.AppendLine();

        if (contract.Methods.Length > 0)
        {
            builder.AppendLine("    // ===== 契约方法转发：MCP 层的轻量语义封装调用这里 =====");
            builder.AppendLine();

            foreach (MethodSpec method in contract.Methods)
            {
                AppendMethod(builder, contract, method);
            }
        }

        builder.AppendLine("}");
        return builder.ToString();
    }

    private static void AppendMethod(StringBuilder builder, ContractSpec contract, MethodSpec method)
    {
        builder.Append("    /// <summary>转发 <c>").Append(contract.ContractName).Append('.')
            .Append(method.Name).AppendLine("</c> 契约方法。</summary>");

        if (method.Description.Length > 0)
        {
            builder.Append("    /// <remarks>").Append(method.Description).AppendLine("</remarks>");
        }

        builder.Append("    public ").Append(method.ReturnTypeName).Append(' ').Append(method.Name).Append('(');
        AppendParameters(builder, method);
        builder.AppendLine(")");

        builder.Append("        => _contract.").Append(method.Name).Append('(');
        AppendArguments(builder, method);
        builder.AppendLine(");");
        builder.AppendLine();
    }

    private static void AppendParameters(StringBuilder builder, MethodSpec method)
    {
        for (int i = 0; i < method.Parameters.Length; i++)
        {
            if (i > 0)
            {
                builder.Append(", ");
            }

            ParamSpec parameter = method.Parameters[i];
            string typeName = parameter.TypeName;

            if (typeName.StartsWith("params ", System.StringComparison.Ordinal))
            {
                builder.Append("params ").Append(typeName.Substring("params ".Length));
            }
            else
            {
                builder.Append(typeName);
            }

            builder.Append(' ').Append(parameter.Name);

            if (parameter.DefaultValueExpression is not null)
            {
                builder.Append(" = ").Append(parameter.DefaultValueExpression);
            }
        }
    }

    private static void AppendArguments(StringBuilder builder, MethodSpec method)
    {
        for (int i = 0; i < method.Parameters.Length; i++)
        {
            if (i > 0)
            {
                builder.Append(", ");
            }

            ParamSpec parameter = method.Parameters[i];
            if (parameter.Omit)
            {
                // 该参数在契约签名里是可选的且被 [AiIgnore] 覆盖，必须用命名参数跳过
                builder.Append(parameter.Name).Append(": ").Append(parameter.Name);
            }
            else
            {
                builder.Append(parameter.Name);
            }
        }
    }

    private static string EmitRegistration(EquatableArray<ContractSpec> contracts)
    {
        var builder = new StringBuilder(4096);

        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("// 由 AI.Extension.Abstractions.Generator 生成，请勿手工修改。");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("#pragma warning disable CS1591");
        builder.AppendLine();
        builder.Append("namespace ").Append(GeneratedRootNamespace).AppendLine(";");
        builder.AppendLine();
        builder.AppendLine("/// <summary>");
        builder.AppendLine("/// 源生成器产出的 DI 注册入口：Swagger 风格的 <c>services.AddAiContractBridges()</c>。");
        builder.AppendLine("/// 在组合根里调用一次，所有契约桥接与契约目录即注册完毕。");
        builder.AppendLine("/// </summary>");
        builder.AppendLine("public static partial class AiContractBridgeRegistration");
        builder.AppendLine("{");
        builder.AppendLine("    /// <summary>注册全部 AI 契约桥接与契约目录（幂等，重复调用安全）。</summary>");
        builder.AppendLine("    public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection AddAiContractBridges(");
        builder.AppendLine("        this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)");
        builder.AppendLine("    {");
        builder.AppendLine("        if (services is null)");
        builder.AppendLine("        {");
        builder.AppendLine("            throw new global::System.ArgumentNullException(nameof(services));");
        builder.AppendLine("        }");
        builder.AppendLine();

        if (contracts.Length > 0)
        {
            builder.AppendLine("        // ===== 桥接类注册（由 [AiContract] 的 Lifetime 决定生命周期） =====");
        }

        foreach (ContractSpec contract in contracts)
        {
            if (!contract.GenerateRegistration)
            {
                continue;
            }

            builder.AppendLine("        global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.TryAdd(");
            builder.AppendLine("            services,");
            builder.Append("            global::Microsoft.Extensions.DependencyInjection.ServiceDescriptor.")
                .Append(contract.Lifetime).Append('<');
            builder.Append(contract.BridgeNamespace).Append('.').Append(contract.BridgeName).Append(", ");
            builder.Append(contract.BridgeNamespace).Append('.').Append(contract.BridgeName).AppendLine(">());");
            builder.AppendLine();
        }

        builder.AppendLine("        // ===== 契约目录注册：UI 诊断面板可直接枚举当前暴露的 AI 契约 =====");
        builder.AppendLine("        global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.TryAdd(");
        builder.AppendLine("            services,");
        builder.AppendLine("            global::Microsoft.Extensions.DependencyInjection.ServiceDescriptor.Singleton(");
        builder.AppendLine("                static provider => new global::AI.Extension.AiContractCatalog(");
        builder.AppendLine("                    new global::AI.Extension.IAiContractBridge[]");
        builder.AppendLine("                    {");
        foreach (ContractSpec contract in contracts)
        {
            if (!contract.GenerateRegistration)
            {
                continue;
            }

            builder.Append("                        global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<")
                .Append(contract.BridgeNamespace).Append('.').Append(contract.BridgeName)
                .AppendLine(">(provider),");
        }

        builder.AppendLine("                    })));");
        builder.AppendLine();
        builder.AppendLine("        return services;");
        builder.AppendLine("    }");
        builder.AppendLine();
        builder.AppendLine("    /// <summary>编译期已知的契约清单（不依赖 DI 容器，便于测试与文档生成）。</summary>");
        builder.AppendLine("    public static global::System.Collections.Generic.IReadOnlyList<global::AI.Extension.AiContractDescriptor> Describe()");
        builder.AppendLine("        => new global::AI.Extension.AiContractDescriptor[]");
        builder.AppendLine("        {");

        foreach (ContractSpec contract in contracts)
        {
            builder.Append("            new global::AI.Extension.AiContractDescriptor(")
                .Append(ContractCollectorFormatting.Literal(contract.ContractFullName)).Append(", ")
                .Append(ContractCollectorFormatting.Literal(contract.ContractName)).AppendLine(",");
            builder.AppendLine("                new global::AI.Extension.AiBridgeMethod[]");
            builder.AppendLine("                {");
            foreach (MethodSpec method in contract.Methods)
            {
                builder.Append("                    new global::AI.Extension.AiBridgeMethod(")
                    .Append(ContractCollectorFormatting.Literal(method.Name)).Append(", ")
                    .Append(ContractCollectorFormatting.Literal(method.Description)).Append(", ")
                    .Append(ContractCollectorFormatting.Literal(method.SuggestedToolName)).AppendLine("),");
            }

            builder.AppendLine("                }),");
        }

        builder.AppendLine("        };");
        builder.AppendLine("}");

        return builder.ToString();
    }
}

internal static class ContractCollectorFormatting
{
    public static string Literal(string value) => ContractCollector.FormatStringLiteral(value);
}
